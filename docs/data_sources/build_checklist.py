#!/usr/bin/env python3
"""Build docs/data_sources/CHECKLIST.md from the per-stream catalogue tables.

One row per catalogued source, for the supervisor review: licence, whether it
was used, how many records it contributed, and a sign-off box. Re-run after a
collection pipeline fills `used` / `records` in USAGE (path -> (records, note)).
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
STREAMS = {
    "kernel_patches.md": "A: kernel patches",
    "other_patches.md": "A: other patches",
    "academic_datasets.md": "A: benchmarks",
    "poc_collections.md": "A: PoCs",
    "vendor_guidance.md": "A: vendor guidance",
    "misc_sources.md": "A: misc",
    "benign_sources.md": "B: benign",
    "riscv_sources.md": "C: RISC-V",
}
NAME_COLS = ("name", "source", "title", "dataset")
URL_COLS = ("url", "artifact url", "repo url")
LIC_COLS = ("licence", "license")

# Filled in as data is collected: catalogue name (as in its table) -> (records, note)
USAGE: dict[str, tuple[int, str]] = {}


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _pick(header: list[str], row: list[str], keys) -> str:
    for i, h in enumerate(header):
        h = h.lower()
        if any(h.startswith(k) for k in keys) and i < len(row):
            return row[i]
    return ""


def rows(md: Path):
    header = None
    for line in md.read_text().splitlines():
        if not line.startswith("|"):
            header = None
            continue
        cells = _cells(line)
        if header is None:
            header = cells
            continue
        if set("".join(cells)) <= set("-: "):
            continue
        name = _pick(header, cells, NAME_COLS)
        if not name:
            continue
        url = re.search(r"https?://[^\s)|>]+", " ".join(cells))
        yield name, url.group(0) if url else _pick(header, cells, URL_COLS), _pick(header, cells, LIC_COLS)


def main() -> None:
    out = ["# Data source checklist (for supervisor review)", "",
           "Generated by `build_checklist.py` from the catalogues in this directory. "
           "Policy (user, 2026-11-05): use every source we can get for results; record each "
           "here so licence and provenance can be cross-checked with the supervisor before "
           "any public release.", "",
           "| # | stream | source | URL | licence | used | records | supervisor OK | note |",
           "|---|---|---|---|---|---|---|---|---|"]
    n = 0
    for fname, stream in STREAMS.items():
        p = HERE / fname
        if not p.exists():
            continue
        for name, url, lic in rows(p):
            n += 1
            rec, note = USAGE.get(name, (0, ""))
            used = "x" if rec else " "
            out.append(f"| {n} | {stream} | {name} | {url} | {lic or '?'} | [{used}] | "
                       f"{rec or ''} | [ ] | {note} |")
    (HERE / "CHECKLIST.md").write_text("\n".join(out) + "\n")
    print(f"wrote CHECKLIST.md ({n} sources)")


if __name__ == "__main__":
    main()
